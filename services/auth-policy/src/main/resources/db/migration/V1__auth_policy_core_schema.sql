CREATE TABLE IF NOT EXISTS auth_users (
    id INT NOT NULL PRIMARY KEY,
    username VARCHAR(128) NOT NULL,
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    company_id INT NOT NULL,
    role VARCHAR(32) NOT NULL,
    group_id VARCHAR(64) NOT NULL,
    CONSTRAINT ux_auth_users_username UNIQUE (username),
    CONSTRAINT ux_auth_users_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS operational_events (
    id VARCHAR(128) NOT NULL PRIMARY KEY,
    occurred_at TIMESTAMP(3) NOT NULL,
    severity VARCHAR(32) NOT NULL,
    category VARCHAR(64) NOT NULL,
    event_type VARCHAR(64),
    source_service VARCHAR(64),
    source VARCHAR(128) NOT NULL,
    message VARCHAR(1024) NOT NULL,
    connections INT NOT NULL,
    latency_ms BIGINT NOT NULL,
    throughput_mbps DOUBLE PRECISION NOT NULL,
    group_id VARCHAR(64) NOT NULL,
    stream_id VARCHAR(128),
    connection_id VARCHAR(128),
    ice_path VARCHAR(32),
    relay_fallback_reason VARCHAR(255)
);

