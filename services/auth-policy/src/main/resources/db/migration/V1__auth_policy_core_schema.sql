CREATE TABLE IF NOT EXISTS gateway_assets (
    gateway_uuid VARCHAR(128) NOT NULL,
    id INT NOT NULL,
    cid VARCHAR(128) NOT NULL,
    uuid VARCHAR(128) NOT NULL,
    company_id INT NOT NULL,
    type VARCHAR(64) NOT NULL,
    name VARCHAR(128) NOT NULL,
    description VARCHAR(512),
    image_url VARCHAR(512),
    status VARCHAR(32) NOT NULL,
    created_at TIMESTAMP(3) NOT NULL,
    updated_at TIMESTAMP(3) NOT NULL,
    group_id VARCHAR(64) NOT NULL,
    PRIMARY KEY (gateway_uuid, uuid)
);

CREATE INDEX IF NOT EXISTS ix_gateway_assets_gateway_group
    ON gateway_assets (gateway_uuid, group_id);

CREATE TABLE IF NOT EXISTS server_health_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_name VARCHAR(128) NOT NULL,
    status VARCHAR(32) NOT NULL,
    checked_at TIMESTAMP(3) NOT NULL,
    latency_ms BIGINT,
    message VARCHAR(512),
    group_id VARCHAR(64) NOT NULL
);

CREATE INDEX IF NOT EXISTS ix_server_health_group_checked
    ON server_health_snapshots (group_id, checked_at);
CREATE INDEX IF NOT EXISTS ix_server_health_group_service_checked
    ON server_health_snapshots (group_id, service_name, checked_at);

CREATE TABLE IF NOT EXISTS stream_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stream_id VARCHAR(128) NOT NULL,
    session_id VARCHAR(128),
    status VARCHAR(32) NOT NULL,
    source VARCHAR(64) NOT NULL,
    started_at TIMESTAMP(3) NOT NULL,
    last_heartbeat_at TIMESTAMP(3) NOT NULL,
    stopped_at TIMESTAMP(3),
    group_id VARCHAR(64) NOT NULL
);

CREATE INDEX IF NOT EXISTS ix_stream_sessions_group_stream_heartbeat
    ON stream_sessions (group_id, stream_id, last_heartbeat_at);
CREATE INDEX IF NOT EXISTS ix_stream_sessions_group_status_heartbeat
    ON stream_sessions (group_id, status, last_heartbeat_at);
