CREATE TABLE IF NOT EXISTS telemetry_latest (
    uuid VARCHAR(128) NOT NULL PRIMARY KEY,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    altitude DOUBLE PRECISION NOT NULL,
    magnetic_x DOUBLE PRECISION NOT NULL,
    magnetic_y DOUBLE PRECISION NOT NULL,
    magnetic_z DOUBLE PRECISION NOT NULL,
    soc VARCHAR(32) NOT NULL,
    phone_battery_soc DOUBLE PRECISION NOT NULL,
    velocity DOUBLE PRECISION NOT NULL,
    total_distance DOUBLE PRECISION NOT NULL,
    epoch_time VARCHAR(32) NOT NULL,
    port_distance DOUBLE PRECISION NOT NULL,
    group_id VARCHAR(64) NOT NULL
);

CREATE INDEX IF NOT EXISTS ix_telemetry_latest_group_uuid
    ON telemetry_latest (group_id, uuid);

